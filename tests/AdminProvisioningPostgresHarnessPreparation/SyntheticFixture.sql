-- install account synchronization for subsequent Admin inserts/updates.
-- This fixture-only trigger mirrors the production identity/login behavior;
-- it does not update admin_id on conflict or weaken any production constraint.
CREATE FUNCTION public.fixture_admin_identity_sync() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
