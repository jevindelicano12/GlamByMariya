CREATE TABLE public.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id uuid NOT NULL UNIQUE,
    email text NOT NULL,
    password_hash text NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.admin_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id uuid NOT NULL UNIQUE,
    username text NOT NULL,
    email text NOT NULL,
    first_name text NOT NULL DEFAULT '',
    last_name text NOT NULL DEFAULT '',
    age_at_registration smallint NOT NULL DEFAULT 0,
    gender text NOT NULL DEFAULT '',
    address text NOT NULL DEFAULT '',
    password_hash text NOT NULL,
    role text NOT NULL,
    is_active boolean NOT NULL DEFAULT false
);

CREATE TABLE public.account_identities (
    id uuid PRIMARY KEY,
    customer_id bigint UNIQUE REFERENCES public.customers(id) ON DELETE RESTRICT,
    admin_id bigint UNIQUE REFERENCES public.admin_users(id) ON DELETE RESTRICT,
    login text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((customer_id IS NOT NULL)::int + (admin_id IS NOT NULL)::int = 1)
);
CREATE UNIQUE INDEX ux_users_email
    ON public.account_identities(lower(btrim(login))) WHERE login IS NOT NULL;

CREATE TABLE public.admin_invitations (
    id uuid PRIMARY KEY,
    email text NOT NULL,
    token_hash text NOT NULL UNIQUE,
    invited_by uuid REFERENCES public.account_identities(id),
    expires_at timestamptz NOT NULL,
    accepted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

